import re
PRE=':root:root '
def split_top(css):
    out=[];d=0;b=''
    for ch in css:
        b+=ch
        if ch=='{':d+=1
        elif ch=='}':
            d-=1
            if d==0: out.append(b);b=''
    return out
def pre(sel):
    r=[]
    for p in [x.strip() for x in sel.split(',') if x.strip()]:
        r.append(p if p.startswith(('html','body','*')) else PRE+p)
    return ',\n'.join(r)
def proc(css):
    css=re.sub(r'/\*.*?\*/','',css,flags=re.S);o=''
    for blk in split_top(css):
        blk=blk.strip()
        if not blk: continue
        h,b=blk.split('{',1);h=h.strip()
        if h.startswith('@keyframes'): o+=blk+'\n'
        elif h.startswith('@media'): o+=h+'{\n'+proc(b.rsplit('}',1)[0])+'}\n'
        else: o+=pre(h)+'{'+b+'\n'
    return o
src=open('redesign.src.css').read()
open('redesign.css','w').write('/* SLYMintX V2 — generated by build_css.py */\n'+proc(src))
